require "digest"
require "json"

module World
  # The TRUE world graph, read from the parsed `.wld` JSON — the reference layer
  # the agent's earned map is drawn against.
  #
  # A PORO that speaks the parser's format, for the same reason Knowledge::Reader
  # is a PORO that speaks SQL: this is another process's output, it has no
  # migrations and Rails must never own it. Nothing here writes.
  #
  # The agent's map and this one are joined on `weak_fingerprint`, and that join
  # is EXACT, not fuzzy. Boukensha's Memory::Fingerprint.weak consumes only the
  # room name, its description and its sorted exit directions, all three of which
  # exist verbatim in the `.wld` source, under a `normalize` that is just
  # `downcase → collapse whitespace → strip`. So the same bytes reach the same
  # hash whether they came off a socket or out of a file. That was verified
  # against live data before this class was written; `test/lib/world/atlas_test.rb`
  # pins the constant, and a boukensha-side test pins the identical constant from
  # `Fingerprint.weak` itself, so a drift in `normalize` fails both suites.
  #
  # What the join CANNOT do is pick a room out of a group that is genuinely
  # identical. tbaMUD's stock world has 2,153 rooms (17%) sharing a weak
  # fingerprint with at least one other room — four "McGintey Center Square"s in
  # zone 315 have the same name, byte-identical prose, and exits that pair them
  # off two and two. No amount of hashing separates those; only a vnum would, and
  # the MUD never sends one. So a match reports a TIER and a LIST of candidates,
  # and every derived claim below degrades to "unverified" rather than picking a
  # winner. Same posture as `confidence: 'provisional'` in the agent's own
  # schema: say what is known, never more.
  class Atlas
    # CircleMUD exit ordering. `D0`..`D5` in the `.wld` source, `dir: 0..5` in
    # the parser's JSON. Also exactly boukensha's RouteFinder::WALKABLE, which is
    # not a coincidence — both are the six the MUD's `move` command accepts.
    DIRECTIONS = %w[north east south west up down].freeze

    # The parser writes `room_linked: -1` for an exit that leads nowhere (a
    # description-only exit, or an unfinished build). It is a real entry in the
    # file and it is not an edge.
    NO_ROOM = -1

    Room = Struct.new(:vnum, :name, :zone, :exits, :weak_fingerprint, :name_desc_key,
                      keyword_init: true)

    class << self
      # Memoized across requests, invalidated by the newest file mtime in the
      # world dir, because 12,701 rooms is ~1s of JSON parsing and the map page
      # polls this every 15s.
      #
      # Deliberately lazy rather than built in `after_initialize`: the world dir
      # is optional (it is generated by `week0_explore/bin/convert-world` and
      # gitignored), so an eager build would make every `rails test` run and
      # every boot pay for a directory most of them do not use. The first
      # request after a rebuild pays once.
      def for_dir(dir)
        dir = Pathname.new(dir)
        stamp = fingerprint_dir(dir)

        MUTEX.synchronize do
          cached = @cache
          return cached[:atlas] if cached && cached[:dir] == dir.to_s && cached[:stamp] == stamp

          atlas = new(dir)
          @cache = { dir: dir.to_s, stamp: stamp, atlas: atlas }
          atlas
        end
      end

      def reset!
        MUTEX.synchronize { @cache = nil }
      end

      private

      # Cheap enough to run per request: one `Dir.glob` plus a stat each. Uses
      # count as well as max mtime so that deleting a file also busts the cache
      # (mtimes only ever move forward).
      def fingerprint_dir(dir)
        files = Dir.glob(dir.join("wld", "*.json"))
        return [ 0, nil ] if files.empty?

        [ files.length, files.map { |f| File.mtime(f).to_f }.max ]
      end
    end

    MUTEX = Mutex.new
    private_constant :MUTEX

    attr_reader :dir

    def initialize(dir)
      @dir = Pathname.new(dir)
      @rooms = {}
      @by_weak = Hash.new { |h, k| h[k] = [] }
      @by_name_desc = Hash.new { |h, k| h[k] = [] }
      load!
    end

    # Absence is a state, not an error — the same rule Knowledge::Reader applies
    # to a knowledge file that does not exist yet. Without the generated JSON the
    # overlay is simply empty and the map renders exactly as it did before.
    def ready? = !@rooms.empty?

    def room_count = @rooms.length
    def zone_count = @rooms.each_value.map(&:zone).uniq.length
    def room(vnum) = @rooms[vnum]

    # How much of this world is not separable by fingerprint alone. Reported so
    # the "ambiguous" tier reads as a property of the world rather than as a bug
    # in the matcher.
    def ambiguous_room_count
      @by_weak.each_value.sum { |vnums| vnums.length > 1 ? vnums.length : 0 }
    end

    # The join. Returns a tier and every candidate — never one guessed winner.
    #
    #   weak       exactly one true room hashes the same. Certain.
    #   ambiguous  several do, and nothing here can separate them.
    #   name_desc  no fingerprint match, but the name and prose are unique.
    #              This is the closed-door case: tbaMUD omits a closed door from
    #              the `[ Exits: ]` line, so the agent's exit set is a subset of
    #              the truth and the weak hash cannot match.
    #   nil        not in this world at all.
    def match(weak_fingerprint:, name:, description:)
      vnums = @by_weak[weak_fingerprint.to_s]
      return { tier: vnums.length == 1 ? "weak" : "ambiguous", vnums: vnums.dup } if vnums.any?

      vnums = @by_name_desc[name_desc_key(name, description)]
      return { tier: vnums.length == 1 ? "name_desc" : "ambiguous", vnums: vnums.dup } if vnums.any?

      nil
    end

    # Where a direction really leads, from a SET of candidate source rooms.
    #
    # Ambiguity does not have to be fatal here, and this is the reason the whole
    # ghost layer still says something useful about a room it cannot pin down:
    # the four identical McGintey rooms disagree about which vnum lies east, but
    # they all agree it is called "McGintey Center Square". So the answer is
    # `certain: true` when the candidates agree on the destination NAME, even
    # where they disagree on its vnum — and the vnum list stays honest either
    # way. If they disagree on the name, nothing is claimed.
    def destination(vnums, direction)
      targets = Array(vnums).filter_map { |v| @rooms[v]&.exits&.[](direction) }
      return nil if targets.empty?

      names = targets.filter_map { |t| @rooms[t]&.name }.uniq
      {
        vnums: targets.uniq,
        # `name` is set only when there is one answer. `names` carries every
        # possibility, so a UI can offer "Toll Booth / McGintey Center Square"
        # instead of a shrug — two candidates is still information, and it beats
        # rendering nothing for a room the agent is about to walk into.
        name: names.length == 1 ? names.first : nil,
        names: names,
        certain: names.length == 1 && !names.first.nil?
      }
    end

    # Every direction the true world gives these rooms, agreed across candidates.
    # A direction only one candidate has is not a fact about "this room".
    def true_directions(vnums)
      lists = Array(vnums).filter_map { |v| @rooms[v]&.exits&.keys }
      return [] if lists.empty?

      lists.reduce(:&).sort_by { |d| DIRECTIONS.index(d) || 99 }
    end

    def zone_of(vnums)
      Array(vnums).filter_map { |v| @rooms[v]&.zone }.uniq.then { |z| z.length == 1 ? z.first : nil }
    end

    def rooms_in_zone(zone)
      @rooms.each_value.count { |r| r.zone == zone }
    end

    # Boukensha's Memory::Fingerprint.weak, reimplemented rather than required:
    # the agent is a separate project with its own Gemfile and this app cannot
    # load it. Duplication is the cost of that boundary; a test on each side
    # asserting the SAME hex constant is what stops the two drifting apart.
    def self.weak_fingerprint(name:, description:, exit_dirs:)
      Digest::SHA256.hexdigest(
        [ normalize(name), normalize(description), Array(exit_dirs).map(&:to_s).sort.join(",") ].join("|")
      )
    end

    # Room prose is wrapped by the MUD at whatever width the client negotiated,
    # so the line breaks belong to the connection, not to the room.
    def self.normalize(text)
      text.to_s.downcase.gsub(/\s+/, " ").strip
    end

    private

    def name_desc_key(name, description)
      [ self.class.normalize(name), self.class.normalize(description) ].join("|")
    end

    def load!
      wld = @dir.join("wld")
      return unless wld.directory?

      Dir.glob(wld.join("*.json")).sort.each do |path|
        parsed = begin
          JSON.parse(File.read(path))
        rescue JSON::ParserError => e
          # One malformed file must not cost the whole atlas. The remaining 188
          # zones are still true.
          Rails.logger.warn("[world] skipping #{path}: #{e.message}") if defined?(Rails)
          next
        end

        Array(parsed).each { |raw| absorb(raw) }
      end
    end

    def absorb(raw)
      return unless raw.is_a?(Hash)

      vnum = raw["id"]
      return unless vnum.is_a?(Integer)

      exits = {}
      Array(raw["exits"]).each do |ex|
        dir = DIRECTIONS[ex["dir"].to_i]
        target = ex["room_linked"]
        next unless dir && target.is_a?(Integer) && target != NO_ROOM

        exits[dir] = target
      end

      name = raw["name"].to_s
      desc = raw["desc"].to_s
      fp = self.class.weak_fingerprint(name: name, description: desc, exit_dirs: exits.keys)
      key = name_desc_key(name, desc)

      @rooms[vnum] = Room.new(
        vnum: vnum, name: name, zone: raw["zone_number"], exits: exits,
        weak_fingerprint: fp, name_desc_key: key
      )
      @by_weak[fp] << vnum
      @by_name_desc[key] << vnum
    end
  end
end
