require "test_helper"

module Api
  module V1
    class WorldControllerTest < ActionDispatch::IntegrationTest
      include KnowledgeFixtures
      include WorldFixtures

      test "the overlay joins the agent's map onto the true world" do
        use_agent_map
        use_world_dir

        get api_v1_world_overlay_path

        assert_response :success
        body = response.parsed_body
        assert body["world_ready"]
        assert_equal 11, body["world"]["rooms"]
        assert_equal 4, body["mapping"].length
        assert_equal [ 5 ], body["unmatched"]
      end

      # Absence is a state. A fresh clone has no world JSON at all — it is
      # generated by week0_explore/bin/convert-world and gitignored — so this is
      # the DEFAULT experience, and it must render an empty overlay over a
      # working map rather than an error over a broken one.
      test "a missing world dir returns 200 with world_ready false" do
        use_agent_map
        use_missing_world_dir

        get api_v1_world_overlay_path

        assert_response :success
        body = response.parsed_body
        assert_not body["world_ready"]
        assert_equal [], body["mapping"]
        assert_equal [], body["ghosts"]
        assert_equal [], body["verdicts"]
      end

      test "a missing knowledge file returns 200 with an empty mapping" do
        use_missing_knowledge_db
        use_world_dir

        get api_v1_world_overlay_path

        assert_response :success
        assert_equal [], response.parsed_body["mapping"]
      end

      # An unmatched room must never 500 the endpoint — an agent standing in a
      # zone nobody has parsed is normal.
      test "rooms with no counterpart report as unmatched rather than erroring" do
        use_agent_map
        use_world_dir(zones: { 2 => WorldFixtures::ZONE_2 })

        get api_v1_world_overlay_path

        assert_response :success
        body = response.parsed_body
        assert body["world_ready"]
        assert_equal [], body["mapping"]
        assert_equal [ 1, 2, 3, 4, 5 ], body["unmatched"].sort
        assert_equal [], body["coverage"]
      end

      test "the payload carries the selected profile like every other envelope" do
        use_agent_map
        use_world_dir

        get api_v1_world_overlay_path

        assert_equal "legacy", response.parsed_body["profile"]
      end

      test "a profile must be selected" do
        use_agent_map
        use_world_dir
        cookies.delete("mud_monitor_profile")

        get api_v1_world_overlay_path

        assert_response :conflict
        assert_equal "profile_selection_required", response.parsed_body["error"]["code"]
      end

      # The one endpoint that reads someone else's DDL gets the same banner the
      # knowledge tab does, rather than a 500 backtrace.
      test "a knowledge file this reader cannot query answers 503, not 500" do
        use_world_dir
        use_knowledge_db(sql: "PRAGMA user_version = 1; CREATE TABLE rooms (id INTEGER PRIMARY KEY);")

        get api_v1_world_overlay_path

        assert_response :service_unavailable
        assert_equal "knowledge_schema_mismatch", response.parsed_body["error"]["code"]
      end
    end
  end
end
